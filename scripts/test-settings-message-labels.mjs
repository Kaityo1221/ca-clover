import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=path=>readFileSync(new URL('../docs/'+path,import.meta.url),'utf8');
const settings=read('settings-accordion.mjs');
const editor=read('exchange-message.mjs');
const index=read('index.html');
assert.ok(settings.includes('💬 一言メッセージ'));
assert.ok(settings.includes('一言メッセージ（最大60文字・改行可）'));
assert.ok(settings.includes('💬 プレビュー'));
assert.ok(!settings.includes('交換時の一言'));
assert.ok(!settings.includes('メダル表示プレビュー'));
assert.ok(!editor.includes('交換時の一言'));
assert.ok(editor.includes('一言メッセージを保存しました。'));
assert.ok(editor.includes('一言メッセージを削除しました。'));
for(const id of ['exchangeMessageInput','exchangeMessageCount','exchangeMessagePreviewText','exchangeMessageSave','exchangeMessageDelete'])assert.ok(settings.includes(id));
assert.ok(editor.includes("const MAX_LENGTH=60"));
assert.ok(editor.includes("const TABLE='ca_exchange_messages'"));
assert.ok(index.includes('./settings-accordion.mjs?v=20261114-message-label1'));
assert.ok(settings.includes('./exchange-message.mjs?v=20261114-message-label1'));
console.log('PASS settings label, preview, feedback, unchanged DOM bindings and DB contract');
